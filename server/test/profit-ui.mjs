// Full distribution flow against an isolated database; never writes school data.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import mongoose from 'mongoose';
import { MongoMemoryReplSet } from 'mongodb-memory-server';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
let mongo, server, browser;
try {
  const output = path.resolve('../artifacts/profit-ui');
  await mkdir(output, { recursive: true });
  mongo = await MongoMemoryReplSet.create({ replSet: { count: 1, storageEngine: 'wiredTiger' } });
  process.env.MONGO_URI = mongo.getUri('profit_ui');
  process.env.JWT_SECRET = 'isolated-profit-ui-key';
  process.env.NODE_ENV = 'test';
  process.env.SERVE_CLIENT = 'true'; process.env.BACKUP_DIR = path.resolve('../.data/qa-browser-backups');
  await mongoose.connect(process.env.MONGO_URI);
  const { createApp } = await import('../src/app.js');
  const { User } = await import('../src/models/User.js');
  const { Partner, PartnerDeposit } = await import('../src/models/Partner.js');
  const { Income, Expense, FinanceCategory } = await import('../src/models/Finance.js');
  const { ProfitDistribution } = await import('../src/models/ProfitDistribution.js');
  const { schoolDate, parseDay } = await import('../src/utils/financeDates.js');
  await Promise.all(Object.values(mongoose.models).map((model) => model.init()));
  const admin = new User({ name: { en: 'Profit Administrator' }, email: 'profit@test.local', role: 'admin' });
  await admin.setPassword('profit-ui-password'); await admin.save();
  const partners = await Partner.create(['Amina Rahman', 'Karim Ahmed'].map((name) => ({ name, phone: '01700000000', address: 'Dhaka' })));
  const date = parseDay(schoolDate());
  await mongoose.models.OpeningBalance.create({ key: 'opening', amountCents: 500000, date: parseDay('2010-01-01'), note: 'Historical starting funds', recordedBy: admin.id });
  await PartnerDeposit.create([10000000, 5000000].map((amountCents, i) => ({ partner: partners[i].id, amountCents, date, requestKey: randomUUID(), recordedBy: admin.id })));
  const [income, excludedIncome, expense, excludedExpense] = await FinanceCategory.create([
    { type: 'income', name: { en: 'School revenue' } }, { type: 'income', name: { en: 'Excluded grant' } },
    { type: 'expense', name: { en: 'School rent' } }, { type: 'expense', name: { en: 'Excluded purchase' } },
  ]);
  await Income.create([{ category: income.id, amount: 10000, date }, { category: excludedIncome.id, amount: 1000, date }]);
  await Expense.create([{ category: expense.id, amount: 2000, date }, { category: excludedExpense.id, amount: 500, date }]);
  server = createApp().listen(0, '127.0.0.1');
  await new Promise((resolve) => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({ headless: true, channel: 'chromium' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  page.setDefaultTimeout(15000);
  const errors = [];
  page.on('pageerror', (err) => errors.push(err.message));
  page.on('response', (r) => { if (r.url().includes('/api/') && r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
  await page.addInitScript(() => { localStorage.setItem('lang', 'en'); localStorage.setItem('i18nextLng', 'en'); });
  await page.goto(base + '/login');
  await page.locator('input[type=email]').fill('profit@test.local');
  await page.locator('input[type=password]').fill('profit-ui-password');
  await page.locator('button[type=submit]').click();
  await page.waitForURL(base + '/');
  await page.goto(base + '/finance?tab=profit');
  await page.getByLabel('Excluded grant', { exact: true }).uncheck();
  await page.getByLabel('Excluded purchase', { exact: true }).uncheck();
  const previewResponse = page.waitForResponse((r) => r.url().endsWith('/api/finance/profit/preview'));
  await page.getByRole('button', { name: 'Calculate net profit', exact: true }).click();
  const preview = (await (await previewResponse).json()).report;
  assert.equal(preview.income, 10000);
  assert.equal(preview.expense, 2000);
  assert.equal(preview.netProfit, 8000);
  const distribute = page.getByRole('button', { name: 'Distribute profit to all partners', exact: true });
  await distribute.waitFor();
  await page.screenshot({ path: path.join(output, 'profit-preview.png'), fullPage: true });
  await page.getByLabel('Excluded grant', { exact: true }).check();
  assert.equal(await distribute.count(), 0, 'Changing selection clears stale preview');
  await page.getByLabel('Excluded grant', { exact: true }).uncheck();
  await page.getByRole('button', { name: 'Calculate net profit', exact: true }).click();
  await distribute.waitFor();
  const recorded = page.waitForResponse((r) => r.url().endsWith('/api/finance/profit/distributions') && r.request().method() === 'POST');
  await distribute.click();
  assert.equal((await recorded).status(), 201);
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some((b) => b.textContent === 'Distribute profit to all partners' && b.disabled));
  await page.locator('details summary').click();
  assert.equal(await ProfitDistribution.countDocuments(), 1);
  await page.screenshot({ path: path.join(output, 'profit-distributed.png'), fullPage: true });
  await page.goto(base + `/partners/${partners[0].id}`);
  await page.getByRole('heading', { name: 'Profit distribution history', exact: true }).waitFor();
  await page.getByText('5,333.33', { exact: false }).first().waitFor();
  await page.screenshot({ path: path.join(output, 'partner-profit.png'), fullPage: true });
  await page.goto(base + '/finance?tab=overview');
  assert.equal(await page.getByRole('button', { name: 'Current balance', exact: true }).count(), 0);
  const current = page.getByRole('region', { name: 'Current balance', exact: true });
  await current.getByText('163,500.00', { exact: false }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Record opening balance', exact: true }).count(), 0);
  assert.equal(await page.getByRole('heading', { name: 'Partner profit payments', exact: true }).count(), 0);
  const payoutRecord = await ProfitDistribution.findOne();
  const payoutToken = await page.evaluate(() => localStorage.getItem('token'));
  const paymentResponse = await page.request.post(base + '/api/finance/balance/profit-payments', {
    headers: { Authorization: `Bearer ${payoutToken}` },
    data: { distribution: payoutRecord.id, partner: partners[0].id, amount: 1000, date: schoolDate(), method: 'bank', reference: 'DEMO-BANK-TRANSFER', requestKey: randomUUID() },
  });
  assert.equal(paymentResponse.status(), 201);
  await current.getByRole('button', { name: 'Refresh', exact: true }).click();
  await current.getByText('162,500.00', { exact: false }).waitFor();
  assert.equal(await page.getByRole('heading', { name: 'Balance statement', exact: true }).count(), 0);
  await page.screenshot({ path: path.join(output, 'current-balance.png'), fullPage: true });
  await page.goto(base + `/partners/${partners[0].id}`);
  await page.getByText('Payment history', { exact: true }).click();
  await page.getByText('DEMO-BANK-TRANSFER', { exact: false }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base + '/finance?tab=overview');
  await current.getByText('162,500.00', { exact: false }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Mobile balance page must not overflow');
  await page.screenshot({ path: path.join(output, 'balance-mobile.png'), fullPage: true });
  await page.goto(base + '/finance?tab=profit');
  await page.getByRole('button', { name: 'Calculate net profit', exact: true }).click();
  await page.getByText('This period overlaps a recorded distribution and cannot be distributed again.', { exact: true }).waitFor();
  assert.equal(await distribute.isDisabled(), true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Mobile page must not overflow horizontally');
  await page.screenshot({ path: path.join(output, 'profit-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto(base + '/activity-logs');
  await page.getByRole('heading', { name: 'Activity logs', exact: true }).waitFor();
  await page.getByRole('link', { name: 'Activity logs', exact: true }).waitFor();
  await page.getByLabel(/^Module/).selectOption('finance');
  await page.getByLabel(/^Action/).selectOption('create');
  await page.getByLabel(/^Result/).selectOption('success');
  await page.getByLabel('Search user or record', { exact: true }).fill('Profit Administrator');
  const logResponse = page.waitForResponse((r) => r.url().includes('/api/activity-logs?') && r.url().includes('module=finance'));
  await page.getByRole('button', { name: 'Apply filters', exact: true }).click();
  const logs = await (await logResponse).json();
  assert.ok(logs.total >= 2, 'distribution and recorded profit payment must both be logged');
  assert.ok(logs.items.every((log) => log.module === 'finance' && log.outcome === 'success' && log.actorEmail === admin.email));
  await page.getByText('View details', { exact: true }).first().click();
  await page.screenshot({ path: path.join(output, 'activity-logs.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Mobile activity page must not overflow');
  await page.screenshot({ path: path.join(output, 'activity-mobile.png'), fullPage: true });
  const accountant = new User({ name: { en: 'Restricted Accountant' }, email: 'restricted@test.local', role: 'accountant' });
  await accountant.setPassword('restricted-test-password'); await accountant.save();
  const restricted = await browser.newPage();
  const restrictedLogin = await restricted.request.post(base + '/api/auth/login', { data: { email: accountant.email, password: 'restricted-test-password' } });
  const restrictedToken = (await restrictedLogin.json()).token;
  await restricted.addInitScript((token) => { localStorage.setItem('token', token); localStorage.setItem('lang', 'en'); }, restrictedToken);
  await restricted.goto(base + '/');
  await restricted.waitForURL(base + '/fees');
  assert.equal(await restricted.getByRole('link', { name: 'Activity logs', exact: true }).count(), 0);
  await restricted.goto(base + '/activity-logs');
  await restricted.waitForURL(base + '/fees');
  assert.equal(await restricted.getByRole('heading', { name: 'Activity logs', exact: true }).count(), 0);
  await restricted.close();
  assert.deepEqual(errors, []);
  console.log('PASS: isolated browser flow verifies finance workflows, admin activity logs and filters, restricted main-menu/direct-page access, and mobile layout.');
} finally {
  await browser?.close();
  if (server) await new Promise((resolve) => server.close(resolve));
  await mongoose.disconnect();
  await mongo?.stop();
}
